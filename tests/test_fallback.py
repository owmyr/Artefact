def test_agent_mid_turn_fallback_preserves_tool_result_without_rerunning_tool(
    tmp_path: Path,
) -> None:
    """Simulate mid-turn fallback: flash calls tool on iter 1, hits 429 on iter 2, pro synthesizes without re-running tool."""
    mock_client = MagicMock()
    test_cascade = ["gemini-2.5-flash", "gemini-2.5-pro", "gemini-2.5-flash-lite"]
    router = GeminiFallbackRouter(client=mock_client, models=test_cascade)
    test_db = tmp_path / "test_emporio.db"
    agent = EmporioAgent(router=router, db_path=test_db)

    call_sequence: list[tuple[str, int]] = []

    def generate_side_effect(
        *,
        model: str,
        contents: list[types.Content],
        config: types.GenerateContentConfig,
    ) -> types.GenerateContentResponse:
        call_sequence.append((model, len(contents)))

        # Iteration 1: gemini-2.5-flash receives [user] (len=1) and requests calculate_payment_options
        if model == "gemini-2.5-flash" and len(contents) == 1:
            return _make_function_call_response(
                name="calculate_payment_options",
                args={"price_brl": 2199.0, "has_active_promotion": False},
            )

        # Iteration 2: gemini-2.5-flash receives [user, model(fc), user(fr)] (len=3) and hits HTTP 429
        if model == "gemini-2.5-flash" and len(contents) == 3:
            raise _make_api_error(
                429,
                "429 RESOURCE_EXHAUSTED: Rate limit reached mid-turn.",
                "RESOURCE_EXHAUSTED",
            )

        # Iteration 2 fallback: gemini-2.5-pro receives the exact same sanitized [user, model(fc), user(fr)] (len=3)
        if model == "gemini-2.5-pro" and len(contents) == 3:
            # Verify cross-model history sanitization on the passed contents
            fc_part = contents[1].parts[0]
            fr_part = contents[2].parts[0]
            assert fc_part.function_call is not None
            assert fc_part.function_call.name == "calculate_payment_options"
            assert fc_part.thought_signature is None
            assert fr_part.function_response is not None
            assert fr_part.function_response.name == "calculate_payment_options"
            assert fr_part.function_response.response["result"]["pix_price_brl"] == 2089.05

            return _make_text_response(
                "O Takamine GD20 custa R$ 2.199,00 na tabela, ou R$ 2.089,05 à vista no PIX (5% de desconto), "
                "e pode ser parcelado em até 12x de R$ 183,25 sem juros."
            )

        raise AssertionError(f"Unexpected call: model={model}, len(contents)={len(contents)}")

    mock_client.models.generate_content.side_effect = generate_side_effect

    with patch("src.agent.execute_tool_call", wraps=agent.tools[1]) as spy_exec:
        # Wrap the actual execute_tool_call function from src.tools to count invocations
        from src import tools as tools_module

        with patch(
            "src.agent.execute_tool_call",
            side_effect=tools_module.execute_tool_call,
        ) as tool_spy:
            result = agent.chat(
                user_message="Quais as opções de pagamento para o Takamine GD20 de R$ 2.199,00?",
                session_id="test_mid_turn_session",
            )

            # Tool must have been executed strictly ONCE despite the mid-turn model switch
            assert tool_spy.call_count == 1

    assert result["model_used"] == "gemini-2.5-pro"
    assert "2.089,05" in result["response"]
    assert len(result["tool_calls"]) == 1
    assert result["tool_calls"][0]["name"] == "calculate_payment_options"
    assert result["tool_calls"][0]["model_requested"] == "gemini-2.5-flash"

    assert len(result["fallback_events"]) == 1
    assert result["fallback_events"][0]["model"] == "gemini-2.5-flash"
    assert result["fallback_events"][0]["status_code"] == 429

    # Verify call sequence: flash (iter 1) -> flash (iter 2, 429) -> pro (iter 2, success)
    assert call_sequence == [
        ("gemini-2.5-flash", 1),
        ("gemini-2.5-flash", 3),
        ("gemini-2.5-pro", 3),
    ]

    # Verify SQLite session persistence stored all 4 turns (user, model fc, user fr, model text)
    persisted_history = agent.load_session_history("test_mid_turn_session")
    assert len(persisted_history) == 4
    assert persisted_history[0].role == "user"
    assert persisted_history[1].role == "model"
    assert persisted_history[1].parts[0].function_call.name == "calculate_payment_options"
    assert persisted_history[2].role == "user"
    assert persisted_history[2].parts[0].function_response.name == "calculate_payment_options"
    assert persisted_history[3].role == "model"
    assert "2.089,05" in persisted_history[3].parts[0].text
