"""Unit tests for Gemini Free-Tier multi-model fallback router and stateful ReAct agent.

Why: Verifies that `GeminiFallbackRouter` and `EmporioAgent` satisfy all invariants
in AGENTS.md Section 3:
- Cascade rotation on HTTP 429 (60s RPM cooldown vs 3600s daily RPD cooldown).
- Retry once on HTTP 503/500/504 (1.5s sleep) followed by 30s cooldown and fallback.
- Permanent model disabling on HTTP 404/400.
- Mid-turn ReAct fallback where a tool call generated by `gemini-2.5-flash` is executed
  once, and after `gemini-2.5-flash` hits HTTP 429 on iteration 2, `gemini-2.5-pro`
  synthesizes the final answer from sanitized `types.Content` history without re-running
  the already-executed tool.
"""

from __future__ import annotations

import time
from pathlib import Path
from typing import Any
from unittest.mock import MagicMock, patch

import pytest
from google.genai import errors, types

from src.agent import EmporioAgent
from src.llm_fallback import GeminiFallbackRouter


def _make_api_error(code: int, message: str, status: str = "ERROR") -> errors.APIError:
    """Create a realistic `google.genai.errors.APIError` instance for unit testing."""
    return errors.APIError(
        code=code,
        response_json={
            "error": {
                "code": code,
                "message": message,
                "status": status,
            }
        },
    )


def _make_text_response(text: str) -> types.GenerateContentResponse:
    """Build a `types.GenerateContentResponse` containing a single text part."""
    part = types.Part.from_text(text=text)
    content = types.Content(role="model", parts=[part])
    candidate = types.Candidate(content=content)
    return types.GenerateContentResponse(candidates=[candidate])


def _make_function_call_response(
    name: str,
    args: dict[str, Any],
) -> types.GenerateContentResponse:
    """Build a `types.GenerateContentResponse` containing a function_call part."""
    part = types.Part.from_function_call(name=name, args=args)
    content = types.Content(role="model", parts=[part])
    candidate = types.Candidate(content=content)
    return types.GenerateContentResponse(candidates=[candidate])


