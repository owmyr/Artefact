# 1. Router Cascade Rotation Tests (429 + 503 -> gemini-2.5-flash-lite)
# ---------------------------------------------------------------------------


@patch("src.llm_fallback.time.sleep", return_value=None)
def test_router_429_and_503_cooldown_and_fallback_to_flash_lite(mock_sleep: MagicMock) -> None:
    """Simulate 429 on gemini-2.5-flash and 503 on gemini-2.5-pro; assert both cooldown and flash-lite succeeds."""
    mock_client = MagicMock()
    test_cascade = ["gemini-2.5-flash", "gemini-2.5-pro", "gemini-2.5-flash-lite"]
    router = GeminiFallbackRouter(client=mock_client, models=test_cascade)

    expected_resp = _make_text_response("Olá! Bem-vindo à Empório da Música.")

    def side_effect(*, model: str, contents: Any, config: Any) -> types.GenerateContentResponse:
        if model == "gemini-2.5-flash":
            raise _make_api_error(
                429,
                "Resource has been exhausted (e.g. check quota). RPM limit reached.",
                "RESOURCE_EXHAUSTED",
            )
        if model == "gemini-2.5-pro":
            raise _make_api_error(
                503,
                "The model is overloaded. Please try again later.",
                "UNAVAILABLE",
            )
        if model == "gemini-2.5-flash-lite":
            return expected_resp
        raise AssertionError(f"Unexpected model called: {model}")

    mock_client.models.generate_content.side_effect = side_effect

    contents = [types.Content(role="user", parts=[types.Part.from_text(text="Olá!")])]
    config = types.GenerateContentConfig(temperature=0.1)

    now_before = time.monotonic()
    response, model_used, fallback_events = router.generate_with_fallback(
        contents=contents,
        config=config,
    )

    assert response == expected_resp
    assert model_used == "gemini-2.5-flash-lite"
    assert len(fallback_events) == 2

    # Event 1: 429 on gemini-2.5-flash (60s cooldown, immediate fallback)
    ev0 = fallback_events[0]
    assert ev0["model"] == "gemini-2.5-flash"
    assert ev0["status_code"] == 429
    assert ev0["cooldown_seconds"] == 60.0
    assert ev0["retried_same_model"] is False
    assert router.model_cooldown_until["gemini-2.5-flash"] >= now_before + 59.0

    # Event 2: 503 on gemini-2.5-pro (retried once after 1.5s sleep, then 30s cooldown)
    ev1 = fallback_events[1]
    assert ev1["model"] == "gemini-2.5-pro"
    assert ev1["status_code"] == 503
    assert ev1["cooldown_seconds"] == 30.0
    assert ev1["retried_same_model"] is True
    assert router.model_cooldown_until["gemini-2.5-pro"] >= now_before + 29.0
    mock_sleep.assert_called_once_with(1.5)

    # Total generate_content calls: 1 (flash) + 2 (pro initial + 1 retry) + 1 (flash-lite) == 4
    assert mock_client.models.generate_content.call_count == 4


def test_router_daily_quota_429_sets_3600s_cooldown_and_404_disables_model() -> None:
    """Verify PerDay/RPD 429 sets a 3600s cooldown and 404 adds model to disabled_models."""
    mock_client = MagicMock()
    test_cascade = ["gemini-2.5-flash", "gemini-2.5-pro", "gemini-2.5-flash-lite"]
    router = GeminiFallbackRouter(client=mock_client, models=test_cascade)

    expected_resp = _make_text_response("Resposta via gemini-2.5-flash-lite.")

    def side_effect(*, model: str, contents: Any, config: Any) -> types.GenerateContentResponse:
        if model == "gemini-2.5-flash":
            raise _make_api_error(
                429,
                "Quota exceeded for metric: GenerateRequestsPerDayPerProjectPerModel (RPD).",
                "RESOURCE_EXHAUSTED",
            )
        if model == "gemini-2.5-pro":
            raise _make_api_error(
                404,
                "Model gemini-2.5-pro is not found for API version.",
                "NOT_FOUND",
            )
        return expected_resp

    mock_client.models.generate_content.side_effect = side_effect

    now_before = time.monotonic()
    response, model_used, fallback_events = router.generate_with_fallback(
        contents=[types.Content(role="user", parts=[types.Part.from_text(text="Teste")])],
        config=types.GenerateContentConfig(),
    )

    assert response == expected_resp
    assert model_used == "gemini-2.5-flash-lite"
    assert len(fallback_events) == 2

    assert fallback_events[0]["model"] == "gemini-2.5-flash"
    assert fallback_events[0]["cooldown_seconds"] == 3600.0
    assert router.model_cooldown_until["gemini-2.5-flash"] >= now_before + 3590.0

    assert fallback_events[1]["model"] == "gemini-2.5-pro"
    assert fallback_events[1]["status_code"] == 404
    assert "gemini-2.5-pro" in router.disabled_models


